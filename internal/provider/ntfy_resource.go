var (
	_ resource.Resource                = &ntfyOutletResource{}
	_ resource.ResourceWithConfigure   = &ntfyOutletResource{}
	_ resource.ResourceWithImportState = &ntfyOutletResource{}
)

type ntfyOutletClient interface {
	CreateNtfyOutlet(context.Context, client.NtfyOutletCreateRequest) (client.NtfyOutlet, error)
	GetNtfyOutlet(context.Context, int64) (client.NtfyOutlet, error)
	UpdateNtfyOutlet(context.Context, int64, client.NtfyOutletUpdateRequest) error
	DeleteNtfyOutlet(context.Context, int64) error
	SetNtfyTopic(context.Context, int64, string) error
	ClearNtfyNotifyPolicy(context.Context, int64) error
	ClearNtfyServerURL(context.Context, int64) error
	DeleteNtfyOutletOperation(context.Context, int64) (client.OutletOperation, error)
	GetTypedOutletStatus(context.Context, string, int64, int64) (client.OutletStatus, error)
}

type ntfyOutletResource struct {
	outletLifecycle[ntfyOutletResourceModel]
}

type ntfyOutletAdapter struct{ client ntfyOutletClient }

type ntfyOutletResourceModel struct {
	ID                types.Int64  `tfsdk:"id"`
	Name              types.String `tfsdk:"name"`
	Description       types.String `tfsdk:"description"`
	Enabled           types.Bool   `tfsdk:"enabled"`
	Topic             types.String `tfsdk:"topic"`
	EffectiveTopic    types.String `tfsdk:"effective_topic"`
	NotifyPolicy      types.String `tfsdk:"notify_policy"`
	ServerURL         types.String `tfsdk:"server_url"`
	ApplyStatus       types.String `tfsdk:"apply_status"`
	LastApplyError    types.String `tfsdk:"last_apply_error"`
	ConfigGeneration  types.Int64  `tfsdk:"config_generation"`
	AppliedGeneration types.Int64  `tfsdk:"applied_generation"`
}

func NewNtfyOutletResource() resource.Resource {
	return &ntfyOutletResource{outletLifecycle: newOutletLifecycle("ntfy Outlet", newNtfyOutletAdapter)}
}

