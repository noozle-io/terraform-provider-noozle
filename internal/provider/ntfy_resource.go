func newNtfyOutletAdapter(providerData any) (outletLifecycleAdapter[ntfyOutletResourceModel], diag.Diagnostics) {
	outletClient, ok := providerData.(ntfyOutletClient)
	if !ok {
		return nil, diag.Diagnostics{diag.NewErrorDiagnostic(
			"Unexpected Provider Data Type",
			fmt.Sprintf("Expected ntfy outlet client, got: %T. Please report this provider bug.", providerData),
		)}
	}
	return ntfyOutletAdapter{client: outletClient}, nil
}

func (a ntfyOutletAdapter) Create(ctx context.Context, _ tfsdk.Config, plan ntfyOutletResourceModel) (outletLifecycleResult[ntfyOutletResourceModel], diag.Diagnostics) {
	ctx, recorder := client.WithOutletOperationRecorder(ctx)
	outlet, err := a.client.CreateNtfyOutlet(ctx, client.NtfyOutletCreateRequest{
		Name:         plan.Name.ValueString(),
		Description:  stringValueOrEmpty(plan.Description),
		Enabled:      plan.Enabled.ValueBool(),
		Topic:        plan.Topic.ValueString(),
		NotifyPolicy: stringPointerValue(plan.NotifyPolicy),
		ServerURL:    stringPointerValue(plan.ServerURL),
	})
	if err != nil {
		return outletLifecycleResult[ntfyOutletResourceModel]{}, diag.Diagnostics{diag.NewErrorDiagnostic("Unable to Create ntfy Outlet", err.Error())}
	}
	if err := observeFinalTypedOutletOperation(ctx, a.client, recorder, "ntfy", outlet.ID, plan.Enabled.ValueBool()); err != nil {
		return outletLifecycleResult[ntfyOutletResourceModel]{}, diag.Diagnostics{diag.NewErrorDiagnostic("Unable to Observe ntfy Outlet Lifecycle", err.Error())}
	}
	return outletLifecycleResult[ntfyOutletResourceModel]{State: ntfyOutletModelFromAPI(outlet, plan.Topic)}, nil
}

func (a ntfyOutletAdapter) Read(ctx context.Context, state ntfyOutletResourceModel) (outletLifecycleResult[ntfyOutletResourceModel], diag.Diagnostics) {
	outlet, err := a.client.GetNtfyOutlet(ctx, state.ID.ValueInt64())
	if err != nil {
		if client.IsNotFound(err) {
			return outletLifecycleResult[ntfyOutletResourceModel]{Removed: true}, nil
		}
		return outletLifecycleResult[ntfyOutletResourceModel]{}, diag.Diagnostics{diag.NewErrorDiagnostic("Unable to Read ntfy Outlet", err.Error())}
	}
	return outletLifecycleResult[ntfyOutletResourceModel]{State: ntfyOutletModelFromAPI(outlet, state.Topic)}, nil
}

func (a ntfyOutletAdapter) Update(ctx context.Context, _ tfsdk.Config, plan, state ntfyOutletResourceModel) (outletLifecycleResult[ntfyOutletResourceModel], diag.Diagnostics) {
	ctx, recorder := client.WithOutletOperationRecorder(ctx)
	if err := a.client.UpdateNtfyOutlet(ctx, state.ID.ValueInt64(), client.NtfyOutletUpdateRequest{
		Name:         plan.Name.ValueString(),
		Description:  stringValueOrEmpty(plan.Description),
		Enabled:      plan.Enabled.ValueBool(),
		Topic:        plan.Topic.ValueString(),
		NotifyPolicy: stringPointerValue(plan.NotifyPolicy),
		ServerURL:    stringPointerValue(plan.ServerURL),
	}); err != nil {
		return outletLifecycleResult[ntfyOutletResourceModel]{}, diag.Diagnostics{diag.NewErrorDiagnostic("Unable to Update ntfy Outlet", err.Error())}
	}
	if plan.NotifyPolicy.IsNull() && !state.NotifyPolicy.IsNull() {
		if err := a.client.ClearNtfyNotifyPolicy(ctx, state.ID.ValueInt64()); err != nil {
			return outletLifecycleResult[ntfyOutletResourceModel]{}, diag.Diagnostics{diag.NewErrorDiagnostic("Unable to Clear ntfy Notify Policy", err.Error())}
		}
	}
	if plan.ServerURL.IsNull() && !state.ServerURL.IsNull() {
		if err := a.client.ClearNtfyServerURL(ctx, state.ID.ValueInt64()); err != nil {
			return outletLifecycleResult[ntfyOutletResourceModel]{}, diag.Diagnostics{diag.NewErrorDiagnostic("Unable to Clear ntfy Server URL", err.Error())}
		}
	}

	outlet, err := a.client.GetNtfyOutlet(ctx, state.ID.ValueInt64())
	if err != nil {
		return outletLifecycleResult[ntfyOutletResourceModel]{}, diag.Diagnostics{diag.NewErrorDiagnostic("Unable to Refresh ntfy Outlet", err.Error())}
	}
	if err := observeFinalTypedOutletOperation(ctx, a.client, recorder, "ntfy", outlet.ID, plan.Enabled.ValueBool()); err != nil {
		return outletLifecycleResult[ntfyOutletResourceModel]{}, diag.Diagnostics{diag.NewErrorDiagnostic("Unable to Observe ntfy Outlet Lifecycle", err.Error())}
	}
	return outletLifecycleResult[ntfyOutletResourceModel]{State: ntfyOutletModelFromAPI(outlet, plan.Topic)}, nil
}

func (a ntfyOutletAdapter) Delete(ctx context.Context, state ntfyOutletResourceModel) diag.Diagnostics {
	operation, err := a.client.DeleteNtfyOutletOperation(ctx, state.ID.ValueInt64())
	if err != nil && !client.IsNotFound(err) {
		return diag.Diagnostics{diag.NewErrorDiagnostic("Unable to Delete ntfy Outlet", err.Error())}
	}
	if err == nil && operation.DesiredGeneration != 0 {
		if err := observeTypedOutletLifecycle(ctx, a.client, "ntfy", state.ID.ValueInt64(), operation.DesiredGeneration, false, true); err != nil {
			return diag.Diagnostics{diag.NewErrorDiagnostic("Unable to Observe ntfy Outlet Lifecycle", err.Error())}
		}
	}
	return nil
}

func ntfyOutletModelFromAPI(outlet client.NtfyOutlet, configuredTopic types.String) ntfyOutletResourceModel {
	if configuredTopic.IsNull() || configuredTopic.IsUnknown() {
		configuredTopic = types.StringValue(outlet.Topic)
	}

	return ntfyOutletResourceModel{
		ID:                types.Int64Value(outlet.ID),
		Name:              types.StringValue(outlet.Name),
		Description:       nullableString(outlet.Description),
		Enabled:           types.BoolValue(outlet.Enabled),
		Topic:             configuredTopic,
		EffectiveTopic:    types.StringValue(outlet.Topic),
		NotifyPolicy:      nullableStringPointer(outlet.NotifyPolicy),
		ServerURL:         nullableStringPointer(outlet.ServerURL),
		ApplyStatus:       nullableString(outlet.ApplyStatus),
		LastApplyError:    nullableString(outlet.LastApplyError),
		ConfigGeneration:  types.Int64Value(outlet.ConfigGeneration),
		AppliedGeneration: types.Int64Value(outlet.AppliedGeneration),
	}
}
